def preprocess_image(pil_image: Image.Image) -> np.ndarray:
    """Reproduce, pixel-pipeline-for-pixel-pipeline, what every current model
    checkpoint was actually trained with: resize original photo -> 224x224
    (nearest). Returns a float32 (224, 224, 3) array — normalization
    (preprocess_input) is applied separately afterward.

    All 4 models (CNN / MobileNetV2 / ResNet50 / Feature Fusion's ResNet50
    branch) share this same plain-resize pipeline — no cropping or background
    removal is used by any deployed checkpoint."""
    arr = np.array(pil_image.convert("RGB"))
    arr = cv2.resize(arr, (224, 224), interpolation=cv2.INTER_NEAREST)
    return arr.astype(np.float32)

