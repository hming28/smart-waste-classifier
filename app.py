# Module-level handoff between the Streamlit script thread and the WebRTC worker
# thread: st.session_state is not readable from the worker, so the live settings
# object is parked here instead.
_LIVE_SETTINGS_HOLDER = {}


def live_video_callback(frame):
    """WebRTC worker-thread callback — one call per incoming camera frame.

    Only every Nth frame is actually classified (`infer_every`); in between, the
    last EMA-smoothed result is redrawn. Without that, CPU-bound inference would
    stall the video pipeline and the label would strobe between classes."""
    import av

    settings = _LIVE_SETTINGS_HOLDER.get("settings")
    bgr_frame = frame.to_ndarray(format="bgr24")

    if settings is None or settings.model is None:
        return av.VideoFrame.from_ndarray(bgr_frame, format="bgr24")

    with settings.lock:
        if settings.mirror:
            bgr_frame = cv2.flip(bgr_frame, 1)

        settings.frame_i += 1
        due = (settings.frame_i % max(settings.infer_every, 1)) == 0

        if due or settings.smoothed is None:
            try:
                probs, cam_box, latency_ms = classify_roi(bgr_frame, settings)
                # EMA over class probabilities. Without it the label flickers
                # between classes on near-tie frames, which reads as "broken"
                # even when the model is behaving exactly as measured.
                if settings.smoothed is None:
                    settings.smoothed = probs
                else:
                    a = settings.ema_alpha
                    settings.smoothed = a * probs + (1.0 - a) * settings.smoothed
                settings.cam_box = cam_box
                settings.latency_ms = latency_ms
            except Exception:
                # A single bad frame must never kill the stream.
                pass

        out = draw_live_overlay(bgr_frame, settings, settings.smoothed,
                                settings.cam_box, settings.latency_ms)

    return av.VideoFrame.from_ndarray(out, format="bgr24")



