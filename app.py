def _hex_to_bgr(hex_color: str) -> tuple:
    """'#2ecc71' -> (113, 204, 46), because OpenCV wants BGR and RECYCLE_INFO
    stores web-style RGB hex."""
    h = hex_color.lstrip("#")
    r, g, b = (int(h[i:i + 2], 16) for i in (0, 2, 4))
    return (b, g, r)


def roi_box(width: int, height: int, ratio: float) -> tuple:
    """Centre square framing guide, sized as `ratio` of the frame's short edge.
    Returns (x0, y0, x1, y1) in pixels."""
    side = int(min(width, height) * ratio)
    x0 = (width - side) // 2
    y0 = (height - side) // 2
    return x0, y0, x0 + side, y0 + side


@st.cache_resource
def get_gradcam_model(model_key: str):
    """Build a Grad-CAM gradient model: input -> (last conv feature map, output).

    Returns None (rather than raising) if the model cannot be introspected — the
    caller degrades to "no attention box" instead of taking the whole tab down.

    The last conv layer is found by scanning backwards for the first 4-D output,
    which resolves to `max_pooling2d_3` (14x14) on AdvancedCNN and `out_relu`
    (7x7x1280) on MobileNetV2 — both the standard Grad-CAM tap points."""
    try:
        model = load_model(MODELS[model_key])
        if isinstance(model, (tf.lite.Interpreter, dict)):
            return None
        # Keras 3: a model loaded from .keras may not expose .inputs until it has
        # been called once, so warm it up on a dummy batch first.
        model(np.zeros((1, 224, 224, 3), dtype=np.float32), training=False)

        last_conv = None
        for layer in reversed(model.layers):
            try:
                if len(layer.output.shape) == 4:
                    last_conv = layer
                    break
            except AttributeError:
                continue
        if last_conv is None:
            return None
        return tf.keras.models.Model(model.inputs, [last_conv.output, model.output])
    except Exception:
        return None


def compute_gradcam_box(grad_model, img_array: np.ndarray, class_index: int,
                        thresh: float = 0.5):
    """Grad-CAM heatmap -> bounding box of the strongest attention blob.

    `img_array` is the same (1, 224, 224, 3) preprocessed tensor the prediction
    used. Returns (x0, y0, x1, y1) NORMALIZED to [0, 1] within the ROI crop, or
    None if no region clears `thresh`.

    This box means "the model's evidence for this class concentrated here". It
    is NOT a detected object boundary."""
    try:
        with tf.GradientTape() as tape:
            conv_out, preds = grad_model(img_array, training=False)
            tape.watch(conv_out)
            score = preds[:, class_index]
        grads = tape.gradient(score, conv_out)
        if grads is None:
            return None

        weights = tf.reduce_mean(grads, axis=(0, 1, 2))
        cam = tf.reduce_sum(conv_out[0] * weights, axis=-1)
        cam = tf.nn.relu(cam).numpy()
        peak = float(cam.max())
        if peak <= 1e-8:
            return None
        cam = cam / peak

        mask = (cam >= thresh).astype(np.uint8) * 255
        mask = cv2.resize(mask, (224, 224), interpolation=cv2.INTER_LINEAR)
        contours, _ = cv2.findContours(mask, cv2.RETR_EXTERNAL, cv2.CHAIN_APPROX_SIMPLE)
        if not contours:
            return None
        x, y, w, h = cv2.boundingRect(max(contours, key=cv2.contourArea))
        return (x / 224.0, y / 224.0, (x + w) / 224.0, (y + h) / 224.0)
    except Exception:
        return None


class LiveSettings:
    """Shared, mutable settings + rolling results for Live Mode.

    Created once per session and stored in st.session_state. The Streamlit
    script thread WRITES the settings on every rerun (when the user moves a
    slider); the WebRTC worker thread only reads them, and writes the results
    back. Both directions are guarded by `lock`. Never touch st.session_state
    from the worker thread — that is not supported by Streamlit."""

    def __init__(self):
        self.lock = threading.Lock()
        # settings (written by the Streamlit script thread)
        self.model = None
        self.model_name = None
        self.grad_model = None
        self.roi_ratio = 0.70
        self.infer_every = 3
        self.ema_alpha = 0.50
        self.use_gradcam = False
        self.mirror = True
        # rolling state (written by the WebRTC worker thread)
        self.frame_i = 0
        self.smoothed = None        # np.ndarray (4,) — EMA of class probabilities
        self.cam_box = None
        self.latency_ms = None


def classify_roi(bgr_frame: np.ndarray, settings):
    """Crop the centre ROI and run it through the selected model's own
    training-time pipeline — identical to the Home tab: plain resize, then that
    model's own preprocess_input.

    Returns (probs (4,), gradcam_box_or_None, latency_ms). Deliberately reuses
    preprocess_image() and PREPROCESS_FUNCS so Live Mode and the Home tab can
    never drift apart on preprocessing."""
    height, width = bgr_frame.shape[:2]
    x0, y0, x1, y1 = roi_box(width, height, settings.roi_ratio)
    crop_rgb = cv2.cvtColor(bgr_frame[y0:y1, x0:x1], cv2.COLOR_BGR2RGB)

    img_array = preprocess_image(Image.fromarray(crop_rgb))
    img_array = np.expand_dims(img_array, axis=0)
    img_array = PREPROCESS_FUNCS[settings.model_name](img_array)

    started = time.perf_counter()
    predictions = predict_with_model(settings.model, img_array)
    latency_ms = (time.perf_counter() - started) * 1000.0

    probs = np.asarray(predictions[0], dtype=np.float32)

    cam_box = None
    if settings.use_gradcam and settings.grad_model is not None:
        cam_box = compute_gradcam_box(settings.grad_model, img_array, int(np.argmax(probs)))

    return probs, cam_box, latency_ms


def draw_live_overlay(bgr_frame: np.ndarray, settings, probs, cam_box, latency_ms):
    """Paint the framing guide, the class-coloured frame border, the label bar,
    the optional Grad-CAM attention box, and the latency readout."""
    height, width = bgr_frame.shape[:2]
    x0, y0, x1, y1 = roi_box(width, height, settings.roi_ratio)

    if probs is None:
        cv2.rectangle(bgr_frame, (x0, y0), (x1, y1), LIVE_GUIDE_BGR, 2)
        cv2.putText(bgr_frame, "Warming up...", (x0, max(y0 - 12, 20)),
                    cv2.FONT_HERSHEY_SIMPLEX, 0.6, LIVE_GUIDE_BGR, 2, cv2.LINE_AA)
        return bgr_frame

    index = int(np.argmax(probs))
    label = CLASS_NAMES[index]
    confidence = float(probs[index])
    confident = confidence >= LIVE_LOW_CONFIDENCE
    color = _hex_to_bgr(RECYCLE_INFO[label]["color"]) if confident else LIVE_UNCERTAIN_BGR

    # 1. Whole-frame border in the class colour. This hugs the frame on purpose:
    #    the result is a CLASSIFICATION of the ROI, not a localisation, so it
    #    would be dishonest to draw it tight around anything.
    cv2.rectangle(bgr_frame, (0, 0), (width - 1, height - 1), color, 10)

    # 2. Centre framing guide.
    cv2.rectangle(bgr_frame, (x0, y0), (x1, y1), LIVE_GUIDE_BGR, 2)

    # 3. Grad-CAM attention box, mapped from ROI-normalized coords back to px.
    if cam_box is not None:
        side = x1 - x0
        cx0 = x0 + int(cam_box[0] * side)
        cy0 = y0 + int(cam_box[1] * side)
        cx1 = x0 + int(cam_box[2] * side)
        cy1 = y0 + int(cam_box[3] * side)
        cv2.rectangle(bgr_frame, (cx0, cy0), (cx1, cy1), LIVE_CAM_BGR, 2)
        cv2.putText(bgr_frame, "model attention", (cx0, max(cy0 - 8, 14)),
                    cv2.FONT_HERSHEY_SIMPLEX, 0.45, LIVE_CAM_BGR, 1, cv2.LINE_AA)

    # 4. Label bar. OpenCV cannot render the emoji used elsewhere in the app, so
    #    this overlay is text-only by necessity.
    text = (f"{label.title()}  {confidence * 100:.1f}%" if confident
            else f"Uncertain ({label.title()} {confidence * 100:.0f}%)")
    (tw, th), _ = cv2.getTextSize(text, cv2.FONT_HERSHEY_SIMPLEX, 0.9, 2)
    cv2.rectangle(bgr_frame, (10, 10), (10 + tw + 24, 10 + th + 24), color, -1)
    cv2.putText(bgr_frame, text, (22, 10 + th + 8),
                cv2.FONT_HERSHEY_SIMPLEX, 0.9, (255, 255, 255), 2, cv2.LINE_AA)

    # 5. Bin hint + latency readout, both bottom-left. They sit here rather than
