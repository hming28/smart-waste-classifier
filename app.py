# ⚠️ READ THIS BEFORE CHANGING ANYTHING BELOW — what Live Mode is and isn't:
#
# Every model in this app is a CLASSIFIER, not an object DETECTOR. The only
# thing any of these checkpoints outputs is a (1, 4) probability vector — there
# is no box/coordinate head anywhere. So Live Mode does NOT "find" objects in
# the frame. What it actually does:
#
#   1. Draws a fixed centre square as a FRAMING GUIDE ("put the item here") and
#      classifies only the pixels inside it. That box is an aiming reticle, not
#      a detection — and cropping to it also keeps the input closer to the
#      single-object, full-frame photos these models were trained on.
#   2. Colours the whole-frame border by the predicted class and overlays the
#      label + confidence for that region.
#   3. Optionally overlays a Grad-CAM box showing WHERE THE MODEL LOOKED. That
#      is an explainability heatmap computed from the classifier's own last conv
#      layer — still not object detection, and it is labelled as such on screen.
#
# Real bounding boxes would need a detector (YOLO etc.), i.e. training a new
# model, which is out of scope. Do not relabel any of this as "detection" in the
# UI without changing the underlying model first.

# ResNet50+CLIP is deliberately excluded: it runs a full PyTorch CLIP encoder
# per frame on top of the ResNet50 branch, which is far too slow for live video.
LIVE_MODELS = ["CNN", "MobileNetV2", "ResNet50"]

# Grad-CAM needs to backprop to an intermediate feature map, so it only works on
# the .keras models — a TFLite interpreter exposes no such tensor.
